package com.dullbits.drawbot.export;

import com.dullbits.drawbot.color.PenDistribution;
import com.dullbits.drawbot.core.DrawingSegment;
import com.dullbits.drawbot.core.Limit;
import com.dullbits.drawbot.core.MachineConfig;
import com.dullbits.drawbot.core.SegmentBuffer;
import java.io.File;
import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Machine G-code generation engine.
 * Faithful and bug-fixed implementation of Gcode.pde:
 *  - Per-pen G-code files with absolute coordinates (G21, G90)
 *  - Pen-up (G1 Z0) and Pen-down (G1 Z1) transitions
 *  - Machine coordinates scaled and offset from image space
 *  - Bounding box test file with 2-inch L-brackets on all 4 corners
 *  - Comprehensive distance, line count, and pen lift statistics in comments
 */
public final class GcodeExporter {

    public static final class ExportResult {
        public final List<File> generatedFiles = new ArrayList<>();
        public final Limit xLimit = new Limit();
        public final Limit yLimit = new Limit();
        public int totalLinesDrawn;
        public float totalDrawingFeet;
        public float totalTraverseFeet;
    }

    private GcodeExporter() {}

    public static ExportResult exportAll(File outputDir, String baseName, SegmentBuffer buffer,
                                         MachineConfig config, PenDistribution distribution,
                                         int displayLineCount, int imgWidth, int imgHeight) throws Exception {
        if (!outputDir.exists()) {
            outputDir.mkdirs();
        }

        ExportResult result = new ExportResult();
        float gcodeScale = config.calculateGcodeScale(imgWidth, imgHeight);
        float offsetX = config.calculateGcodeOffsetX(imgWidth, gcodeScale);
        float offsetY = config.calculateGcodeOffsetY(imgHeight, gcodeScale);

        int lineCount = Math.min(displayLineCount, buffer.getLineCount());
        int penCount = config.getPenCount();

        // 1. Export per-pen files
        for (int p = 0; p < penCount; p++) {
            String markerCode = distribution.getMarkerCodeForPen(p);
            String filename = "gcode_" + baseName + "_pen" + p + "_" + markerCode + ".txt";
            File gcodeFile = new File(outputDir, filename);

            boolean isPenDown = false;
            int penLifts = 2;
            float penMovement = 0.0f;
            float penDrawing = 0.0f;
            int linesDrawn = 0;
            float currentX = 0.0f;
            float currentY = 0.0f;

            try (PrintWriter out = new PrintWriter(gcodeFile, StandardCharsets.UTF_8.name())) {
                // Header comments
                out.println("(Generated by Drawbot Studio)");
                out.println("(Source image: " + baseName + ")");
                out.println("(Pen: " + p + " - " + markerCode + ")");
                out.println("(G-code scale: " + config.formatGcodeNumber(gcodeScale) + ")");
                out.println("(Offsets X: " + config.formatGcodeNumber(offsetX) + ", Y: " + config.formatGcodeNumber(offsetY) + ")");

                // G-code machine initialization
                out.println("G21");    // Metric units (millimeters)
                out.println("G90");    // Absolute positioning
                out.println("G1 Z0");  // Pen up

                for (int i = 0; i < lineCount; i++) {
                    DrawingSegment seg = buffer.get(i);
                    if (seg.penNumber == p) {
                        float scaledX1 = seg.x1 * gcodeScale + offsetX;
                        float scaledY1 = seg.y1 * gcodeScale + offsetY;
                        float scaledX2 = seg.x2 * gcodeScale + offsetX;
                        float scaledY2 = seg.y2 * gcodeScale + offsetY;

                        float segDist = (float) Math.hypot(scaledX2 - scaledX1, scaledY2 - scaledY1);

                        // If line start differs from current position, rapid traverse with pen up
                        if (currentX != scaledX1 || currentY != scaledY1) {
                            out.println("G1 Z0");
                            isPenDown = false;
                            float traverseDist = (float) Math.hypot(scaledX1 - currentX, scaledY1 - currentY);
                            out.println("G1 X" + config.formatGcodeNumber(scaledX1) + " Y" + config.formatGcodeNumber(scaledY1));
                            currentX = scaledX1;
                            currentY = scaledY1;
                            penMovement += traverseDist;
                            penLifts++;
                        }

                        if (seg.penDown) {
                            if (!isPenDown) {
                                out.println("G1 Z1");
                                isPenDown = true;
                            }
                            penDrawing += segDist;
                            linesDrawn++;
                        } else {
                            if (isPenDown) {
                                out.println("G1 Z0");
                                isPenDown = false;
                                penMovement += segDist;
                                penLifts++;
                            }
                        }

                        out.println("G1 X" + config.formatGcodeNumber(scaledX2) + " Y" + config.formatGcodeNumber(scaledY2));
                        currentX = scaledX2;
                        currentY = scaledY2;

                        if (seg.penDown) {
                            result.xLimit.update(scaledX2);
                            result.yLimit.update(scaledY2);
                        }
                    }
                }

                // Machine trailer
                out.println("G1 Z0");
                out.println("G1 X" + config.formatGcodeNumber(0.10f) + " Y" + config.formatGcodeNumber(0.10f));
                out.println("G1 X0 Y0"); // Capitalized Y for standard G-code compliance

                float drawingFeet = penDrawing / 25.4f / 12.0f;
                float traverseFeet = penMovement / 25.4f / 12.0f;
                out.println("(Drew " + linesDrawn + " lines for " + String.format("%.2f", drawingFeet) + " feet)");
                out.println("(Pen was lifted " + penLifts + " times for " + String.format("%.2f", traverseFeet) + " feet)");
                out.println("(Extremes of X: " + config.formatGcodeNumber(result.xLimit.min) + " thru " + config.formatGcodeNumber(result.xLimit.max) + ")");
                out.println("(Extremes of Y: " + config.formatGcodeNumber(result.yLimit.min) + " thru " + config.formatGcodeNumber(result.yLimit.max) + ")");

                result.totalLinesDrawn += linesDrawn;
                result.totalDrawingFeet += drawingFeet;
                result.totalTraverseFeet += traverseFeet;
            }
            result.generatedFiles.add(gcodeFile);
        }

        // 2. Export boundary test file
        File testFile = new File(outputDir, "gcode_" + baseName + "_test.txt");
        float testLength = 25.4f * 2.0f; // 2-inch L marks
        try (PrintWriter out = new PrintWriter(testFile, StandardCharsets.UTF_8.name())) {
            out.println("(This is a test file to draw the extremes of the drawing area.)");
            out.println("(Draws a 2 inch mark on all four corners of the paper.)");
            out.println("(WARNING: pen will be down.)");
            out.println("(Extremes of X: " + config.formatGcodeNumber(result.xLimit.min) + " thru " + config.formatGcodeNumber(result.xLimit.max) + ")");
            out.println("(Extremes of Y: " + config.formatGcodeNumber(result.yLimit.min) + " thru " + config.formatGcodeNumber(result.yLimit.max) + ")");
            out.println("G21");
            out.println("G90");
            out.println("G1 Z0");

            float minX = result.xLimit.hasBounds() ? result.xLimit.min : 0.0f;
            float maxX = result.xLimit.hasBounds() ? result.xLimit.max : config.getImageWidthMm();
            float minY = result.yLimit.hasBounds() ? result.yLimit.min : 0.0f;
            float maxY = result.yLimit.hasBounds() ? result.yLimit.max : config.getImageHeightMm();

            // Upper left
            out.println("(Upper left)");
            out.println("G1 X" + config.formatGcodeNumber(minX) + " Y" + config.formatGcodeNumber(minY + testLength));
            out.println("G1 Z1");
            out.println("G1 X" + config.formatGcodeNumber(minX) + " Y" + config.formatGcodeNumber(minY));
            out.println("G1 X" + config.formatGcodeNumber(minX + testLength) + " Y" + config.formatGcodeNumber(minY));
            out.println("G1 Z0");

            // Upper right
            out.println("(Upper right)");
            out.println("G1 X" + config.formatGcodeNumber(maxX - testLength) + " Y" + config.formatGcodeNumber(minY));
            out.println("G1 Z1");
            out.println("G1 X" + config.formatGcodeNumber(maxX) + " Y" + config.formatGcodeNumber(minY));
            out.println("G1 X" + config.formatGcodeNumber(maxX) + " Y" + config.formatGcodeNumber(minY + testLength));
            out.println("G1 Z0");

            // Lower right
            out.println("(Lower right)");
            out.println("G1 X" + config.formatGcodeNumber(maxX) + " Y" + config.formatGcodeNumber(maxY - testLength));
            out.println("G1 Z1");
            out.println("G1 X" + config.formatGcodeNumber(maxX) + " Y" + config.formatGcodeNumber(maxY));
            out.println("G1 X" + config.formatGcodeNumber(maxX - testLength) + " Y" + config.formatGcodeNumber(maxY));
            out.println("G1 Z0");

            // Lower left
            out.println("(Lower left)");
            out.println("G1 X" + config.formatGcodeNumber(minX + testLength) + " Y" + config.formatGcodeNumber(maxY));
            out.println("G1 Z1");
            out.println("G1 X" + config.formatGcodeNumber(minX) + " Y" + config.formatGcodeNumber(maxY));
            out.println("G1 X" + config.formatGcodeNumber(minX) + " Y" + config.formatGcodeNumber(maxY - testLength));
            out.println("G1 Z0");

            out.println("G1 Z0");
            out.println("G1 X0 Y0");
        }
        result.generatedFiles.add(testFile);

        return result;
    }
}
